# 下記の台形の面積を計算する
上辺 = 10
下辺 = 20
高さ = 5
# 台形の面積の公式: (上辺 + 下辺) *高さ / 2
面積 = (上辺 + 下辺 ) * 高さ / 2
print(f"台形の面積は {面積}cm²　です。")